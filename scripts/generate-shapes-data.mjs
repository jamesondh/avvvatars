import fs from "fs/promises";
import path from "path";
import { fileURLToPath } from "url";

// Derive __dirname in ES Module
const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const shapesFilePath = path.resolve(__dirname, "../src/shape/shapes.tsx");
const outputFilePath = path.resolve(__dirname, "../src/core/shapes-data.ts");

// Regex to find exported shape components and capture the name (ShapeN) and inner SVG content
// It looks for `export const ShapeN = ... => (` followed by `<svg ...>` and captures everything until `</svg>)`
// It handles potential multi-line SVG content using the [\s\S]*? pattern.
const shapeRegex =
  /export\s+const\s+(Shape\d+)\s*=\s*\([^)]*\)\s*=>\s*\(\s*<svg[^>]*>([\s\S]*?)<\/svg>\s*\);?/gs;

async function generateShapesData() {
  try {
    console.log(`Reading shapes file from: ${shapesFilePath}`);
    const shapesFileContent = await fs.readFile(shapesFilePath, "utf-8");
    console.log("Successfully read shapes file.");

    const shapesData = {};
    let match;
    let count = 0;

    console.log("Starting regex matching...");
    // Reset lastIndex before starting the loop
    shapeRegex.lastIndex = 0;

    while ((match = shapeRegex.exec(shapesFileContent)) !== null) {
      count++;
      const shapeName = match[1];
      // Trim whitespace and newlines from the captured SVG content
      const svgContent = match[2].trim();

      if (shapeName && svgContent) {
        shapesData[shapeName] = { svgContent };
        // console.log(`  Found ${shapeName}`);
      } else {
        console.warn(`  Skipped invalid match at index ${match.index}`);
      }
      // Prevent infinite loops with zero-width matches (though unlikely with this regex)
      if (match.index === shapeRegex.lastIndex) {
        shapeRegex.lastIndex++;
      }
    }

    console.log(`Finished regex matching. Found ${count} shapes.`);

    if (Object.keys(shapesData).length === 0) {
      console.error(
        "No shapes found! Check the regex or the input file format."
      );
      process.exit(1);
    }

    // Prepare the output file content
    const outputContent = `// Generated by scripts/generate-shapes-data.mjs
// Do not edit this file manually.

import { ShapeData } from './types';

export const SHAPES_DATA: Record<string, ShapeData> = ${JSON.stringify(
      shapesData,
      null,
      2
    )};
`;

    console.log(`Writing generated data to: ${outputFilePath}`);
    await fs.writeFile(outputFilePath, outputContent, "utf-8");
    console.log("Successfully generated src/core/shapes-data.ts");
  } catch (error) {
    console.error("Error generating shapes data:", error);
    process.exit(1);
  }
}

generateShapesData();
